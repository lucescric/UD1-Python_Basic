# declaració de variables
x = int(input("Inserta el número x "))
y = int(input("Inserta el número y "))

# operacions
print(f"El valor de x es {x} i el valor de y es {y}")
print(f"La suma total es:{x+y}")
print(f"La resta total es:{y-x}")
print(f"La multiplicació total es:{y+x}")
print(f"La divisió total es:{y/x}")  # divisió
print(f"La divisió sensera es:{y//x}")  # divisió entera
print(f"El resot de la divisió es:{y%x}")  # resto de la divisio
